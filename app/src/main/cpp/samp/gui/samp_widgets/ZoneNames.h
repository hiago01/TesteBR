	inline int AreaAt(float x, float y, float z, int first, int last)   // procura de tras para frente (mais especifico primeiro)
	{
		for (int i = last; i >= first; i--)
		{
			const Area& a = kAreas[i];
			if (x >= a.x0 && x < a.x1 && y >= a.y0 && y < a.y1 && z >= a.z0 && z < a.z1) return a.id;
		}
		return -1;
	}

	// Escreve "Cidade | Zona" (ou so um nome quando a zona e a propria cidade). Fora do mapa: "San Andreas".
	inline void Describe(float x, float y, float z, char* out, size_t n)
	{
		int zone = AreaAt(x, y, z, 0, kAreaCount - 1);
		const int city = AreaAt(x, y, 0.0f, 0, kCityAreas - 1);
		auto isCity = [](int id) { for (int i = 0; i < kCityAreas; i++) if (kAreas[i].id == id) return true; return false; };
		if (zone < 0 || isCity(zone))   // ponte/viaduto acima do alcance vertical das zonas: usa a zona de baixo (z = 0)
		{
			const int z2 = AreaAt(x, y, 0.0f, 0, kAreaCount - 1);
			if (z2 >= 0 && !isCity(z2)) zone = z2;
		}
		const char* zn = (zone >= 0 && zone < kNameCount) ? kNames[zone] : nullptr;
		const char* cn = (city >= 0 && city < kNameCount) ? kNames[city] : nullptr;
		size_t k = 0;
		auto put = [&](const char* s) { while (s && *s && k + 1 < n) out[k++] = *s++; };
		if (!zn && !cn) put("San Andreas");
		else if (!zn || zn == cn || (cn && zn && city == zone)) put(zn ? zn : cn);
		else if (!cn) put(zn);
		else { put(cn); put(" | "); put(zn); }
		if (n) out[k] = 0;
	}
